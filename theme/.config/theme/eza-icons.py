#!/usr/bin/env python3
"""Writes templates/eza-theme.yml.tpl, eza's icons, from yazi's: yazi's own icons for the
installed version (its preset theme from GitHub) with icons.toml on top (folders by name in
accent, any file names and extensions listed there). hyprdori-theme-set then renders it to
~/.config/eza/theme.yml, so eza and yazi show the same icons. Run it again after a yazi update
or a change to icons.toml.

  eza-icons.py              fetch yazi's preset for the installed version
  eza-icons.py PRESET.toml  use an existing preset

Colors only matter for the icons: LS_COLORS and EZA_COLORS (zsh-colors.zsh) take precedence
for names and everything else, and eza draws an icon in its own style from this file.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICONS = HERE / "icons.toml"
OUTPUT = HERE / "templates/eza-theme.yml.tpl"


def yazi_preset(argv: list[str]) -> dict:
    if argv:
        return tomllib.loads(Path(argv[0]).read_text())
    version = re.search(r"Version:\s*([\d.]+)", subprocess.run(["yazi", "--version"], capture_output=True, text=True).stdout)
    if not version:
        raise SystemExit("Can't tell yazi's version; pass its preset theme-dark.toml")
    url = f"https://raw.githubusercontent.com/sxyazi/yazi/v{version.group(1)}/yazi-config/preset/theme-dark.toml"
    with urllib.request.urlopen(url, timeout=20) as response:
        return tomllib.loads(response.read().decode())


def color(value: str) -> str:
    """A theme color name becomes a {{ placeholder }}; a hex value stays."""
    return value if value.startswith("#") else "{{ " + value + " }}"


def our_icons() -> tuple[dict, dict, dict]:
    icons = tomllib.loads(ICONS.read_text())
    dirs = {n: (d["icon"], "{{ accent }}") for d in icons.get("dir", []) for n in d.get("names", [])}
    files = {n: (f["icon"], color(f.get("color", "text"))) for f in icons.get("file", []) for n in f.get("names", [])}
    exts = {n: (e["icon"], color(e.get("color", "text"))) for e in icons.get("ext", []) for n in e.get("names", [])}
    return dirs, files, exts


def entry(glyph: str, color: str) -> str:
    return "{icon: {glyph: " + json.dumps(glyph, ensure_ascii=False) + ", style: {foreground: " + json.dumps(color) + "}}}"


def main(argv: list[str]) -> int:
    preset = yazi_preset(argv)["icon"]
    dirs, files, exts = our_icons()

    # eza matches folders and files by name in one list: yazi's, then ours on top
    filenames = {e["name"]: (e["text"], e["fg"]) for e in preset.get("files", [])}
    filenames.update({e["name"]: (e["text"], "{{ accent }}") for e in preset.get("dirs", [])})
    filenames.update(dirs)
    filenames.update(files)
    extensions = {e["name"]: (e["text"], e["fg"]) for e in preset.get("exts", [])}
    extensions.update(exts)

    out = [
        "# {{ theme_name }}, generated by hyprdori-theme-set from templates/eza-theme.yml.tpl.",
        "# The template comes from yazi's icons and icons.toml (theme/.config/theme/eza-icons.py):",
        "# edit icons.toml and run that script instead.",
        "filenames:",
        *(f"  {json.dumps(name, ensure_ascii=False)}: {entry(*v)}" for name, v in sorted(filenames.items())),
        "extensions:",
        *(f"  {json.dumps(name, ensure_ascii=False)}: {entry(*v)}" for name, v in sorted(extensions.items())),
    ]
    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"{OUTPUT}: {len(filenames)} file names, {len(extensions)} extensions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
